-- =====================================================================
-- V37: Координаты карточки локации на «карте дела».
--
-- Отдельная сущность от entry_x/entry_y (это точка входа игрока
-- на сцене локации). Здесь — где стоит карточка на доске админки.
--
-- В пикселях, потому что карта большая и скроллится. Карточка 200×80,
-- дефолтное расположение — сетка слева-сверху.
-- =====================================================================

ALTER TABLE locations
    ADD COLUMN map_x INTEGER NOT NULL DEFAULT 60,
    ADD COLUMN map_y INTEGER NOT NULL DEFAULT 60;

COMMENT ON COLUMN locations.map_x IS 'X карточки на карте дела (px)';
COMMENT ON COLUMN locations.map_y IS 'Y карточки на карте дела (px)';