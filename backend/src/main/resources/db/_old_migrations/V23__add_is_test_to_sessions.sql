-- =====================================================================
-- V23: Тестовые сессии.
--
-- is_test = true → сессия создана админом для проверки кейса.
-- Используется чтобы:
--   - отличать в аналитике (позже);
--   - не учитывать в бизнес-метриках;
--   - фильтровать в списках «Мои сессии» (опционально).
--
-- По умолчанию false — все существующие сессии не тестовые.
-- =====================================================================

ALTER TABLE game_sessions
    ADD COLUMN is_test BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN game_sessions.is_test IS 'Сессия создана в тестовом режиме (админка)';